// ClientRepair repairs only the invoking user's saved wiring. Classification and
// merge use one manifest snapshot under client.lock; enrollment is never renewed.
// os.Root confinement follows https://go.dev/blog/osroot#introducing-osroot.
func ClientRepair(home string) (ClientResult, error) {
	result := ClientResult{Action: "repair"}
	if !filepath.IsAbs(home) {
		return result, errors.New("repair requires an absolute user home")
	}
	home = filepath.Clean(home)
	root, err := openDriftRoot(home)
	if err != nil {
		return result, fmt.Errorf("repair user home: %w", err)
	}
	defer root.Close()
	dir := ".aegishook-client"
	lockPath := filepath.Join(dir, "client.lock")
	var lock *os.File
	if st, e := root.Lstat(lockPath); os.IsNotExist(e) {
		lock, err = root.OpenFile(lockPath, os.O_CREATE|os.O_EXCL|os.O_RDWR, 0600)
	} else if e == nil && st.Mode().IsRegular() {
		// O_RDWR opens a substituted FIFO without waiting for a peer on Unix;
		// the opened-handle check rejects it before locking (POSIX open(2)).
		lock, err = root.OpenFile(lockPath, os.O_RDWR, 0)
		if err == nil {
			st, err = lock.Stat()
			if err == nil && !st.Mode().IsRegular() {
				err = errors.New("repair lock is not regular")
			}
		}
	} else {
		err = errors.New("repair lock is not a regular file")
	}
	if lock != nil {
		defer lock.Close()
	}
	if err != nil {
		return result, fmt.Errorf("repair client lock: %w", err)
	}
	if err = lockProcessFile(lock); err != nil {
		return result, errors.New("another client operation is in progress")
	}
	manifestPath := filepath.Join(dir, "client.json")
	data, err := readDriftFile(root, manifestPath)
	var manifest clientManifest
	if err != nil || !validDriftJSON(data) || json.Unmarshal(data, &manifest) != nil || manifest.Format != 1 || len(manifest.NodeID) != 32 {
		return result, errors.New("repair requires a valid existing client manifest")
	}
	if err = clientRepairEnrollment(root, dir, manifest.NodeID); err != nil {
		return result, err
	}
	roots := map[string]*os.Root{home: root}
	defer func() {
		for _, r := range roots {
			if r != nil && r != root {
				_ = r.Close()
			}
		}
	}()
	edits := []clientEdit{}
	for _, entry := range manifest.Entries {
		state := OwnerNotEvaluated
		if entry.Agent != "cursor" || entry.Scope != "enterprise" {
			state = driftEntryState(home, root, roots, entry.Installation)
		}
		switch state {
		case OwnedExact:
			continue
		case OwnerMissing, OwnerFileMissing:
			target, rel := driftTargetRoot(home, root, roots, entry.Installation)
			edit, e := clientRepairEdit(target, rel, entry)
			if e != nil {
				return result, fmt.Errorf("prepare repair %s: %w", entry.Entry, e)
			}
			// Generated bytes must remain readable by drift checks and rollback.
			if len(edit.after) > clientDriftMaxBytes {
				result.Retained = append(result.Retained, entry.Entry)
				result.Remaining = len(manifest.Entries)
				result.Warning = "Generated hook document exceeds the config parse budget; no entries changed."
				return result, nil
			}
			edits = append(edits, edit)
		default:
			result.Retained = append(result.Retained, entry.Entry)
		}
	}
	// Preserve the raw manifest, including ownership history and unknown fields.
	// A final identical-byte edit is a snapshot recheck/commit barrier and is never
	// regenerated from current runtime defaults or enrollment/trust state.
	if len(edits) > 0 {
		edits = append(edits, clientEdit{root: root, path: manifestPath, before: data, after: data, mode: 0600, existed: true})
		if err = applyClientRepairEdits(edits); err != nil {
			return result, err
		}
	}
	result.Remaining = len(manifest.Entries)
	if len(result.Retained) > 0 {
		result.Warning = "Modified, unreadable or unevaluated entries retained; inspect them before repair."
	}
	return result, nil
}

func clientRepairEnrollment(root *os.Root, dir, nodeID string) error {
	for _, name := range []string{filepath.Join("adapter", "connection.json"), "enrolled.json"} {
		data, err := readDriftFile(root, filepath.Join(dir, name))
		if os.IsNotExist(err) {
			continue
		}
		var saved ClientConnection
		if err != nil || !validDriftJSON(data) || json.Unmarshal(data, &saved) != nil || saved.NodeID != nodeID || len(saved.Token) != 64 || strings.ContainsAny(saved.Token, "\r\n") {
			return errors.New("repair requires a valid saved enrollment matching the manifest")
		}
		if _, err = localaddr.Endpoint(saved.Endpoint); err != nil {
			return errors.New("repair enrollment endpoint is invalid")
		}
		if saved.BundleTrust != nil {
			if _, err = BootstrapPolicyTrust(saved.BundlePublicKey, saved.BundleTrust); err != nil {
				return errors.New("repair enrollment trust is invalid")
			}
		}
		return nil
	}
	return errors.New("repair requires existing enrollment; install first")
}

func clientRepairEdit(root *os.Root, rel string, v clientEntry) (clientEdit, error) {
	edit := clientEdit{root: root, path: rel, mode: 0600}
	if root == nil || !filepath.IsLocal(rel) {
		return edit, errors.New("repair target is not confined")
	}
	if v.Agent == "pi" {
		if v.ManagedContent == "" {
			return edit, errors.New("missing Pi ownership snapshot")
		}
		st, err := root.Lstat(rel)
		if err == nil {
			if st.Mode()&os.ModeSymlink == 0 {
				return edit, errors.New("Pi entry is not owned")
			}
			edit.oldLink, err = root.Readlink(rel)
			if err != nil || edit.oldLink != v.ManagedContent {
				return edit, errors.New("Pi entry changed")
			}
			edit.existed = true
		} else if !os.IsNotExist(err) {
			return edit, err
		}
		edit.newLink = v.ManagedContent
		return edit, nil
	}
	data, err := readDriftFile(root, rel)
	if err != nil && !os.IsNotExist(err) {
		return edit, err
	}
	if err == nil {
		edit.existed = true
		edit.before = data
		st, e := root.Lstat(rel)
		if e != nil {
			return edit, e
		}
		edit.mode = st.Mode().Perm()
	}
	if v.Agent == "opencode" {
		if v.ManagedContent == "" || edit.existed && string(data) != v.ManagedContent {
			return edit, errors.New("OpenCode entry changed or has no ownership snapshot")
		}
		edit.after = []byte(v.ManagedContent)
		return edit, nil
	}
	if v.ManagedCommand == "" {
		return edit, errors.New("missing command ownership snapshot")
	}
	for _, event := range hookEvents(v.Agent) {
		if len(hookGroup(v.Installation, event)) == 0 {
			return edit, errors.New("invalid group ownership snapshot")
		}
	}
	doc := map[string]any{}
	if edit.existed {
		state := driftGroups(data, v.Installation)
		if state != OwnerMissing && state != OwnedExact {
			return edit, errors.New("hook ownership changed before repair")
		}
		if !validDriftJSON(data) || json.Unmarshal(data, &doc) != nil {
			return edit, errors.New("invalid hook document")
		}
	}
	edit.after, _, _, err = mergeHookDocument(v.Installation, true, doc, edit.before, edit.mode)
	return edit, err
}

func checkConfinedClientEdit(e clientEdit, undo bool) error {
	expected, link, exists := e.before, e.oldLink, e.existed
	if undo {
		expected, link, exists = e.after, e.newLink, e.after != nil || e.newLink != ""
	}
	st, err := e.root.Lstat(e.path)
	if !exists && os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return errors.New("repair target changed during operation")
	}
	if !exists {
		return errors.New("repair target appeared during operation")
	}
	if link != "" {
		got, err := e.root.Readlink(e.path)
		if err == nil && got == link {
			return nil
		}
	} else if st.Mode().IsRegular() {
		got, err := readDriftFile(e.root, e.path)
		if err == nil && bytes.Equal(got, expected) {
			return nil
		}
	}
	return errors.New("repair target changed during operation")
}

// The same expected-byte rule governs forward edits and reverse-order rollback.
// Named #39 limit: recheck+rename is not CAS; in-root concurrent edits remain a
// residual race. Root confinement prevents redirected/out-of-root writes.
func applyConfinedClientEdit(e clientEdit, undo bool) error {
	if err := checkConfinedClientEdit(e, undo); err != nil {
		return err
	}
	data, link := e.after, e.newLink
	if undo {
		data, link = e.before, e.oldLink
	}
	if data == nil && link == "" {
		return e.root.Remove(e.path)
	}
	if bytes.Equal(e.before, e.after) && e.oldLink == e.newLink {
		return nil
	}
	if err := e.root.MkdirAll(filepath.Dir(e.path), 0700); err != nil {
		return err
	}
	if link != "" {
		return e.root.Symlink(link, e.path)
	}
	// AtomicFile's write/sync/close/rename sequence, bound to the acquired root.
	temp := filepath.Join(filepath.Dir(e.path), ".aegis-"+ID())
	file, err := e.root.OpenFile(temp, os.O_CREATE|os.O_EXCL|os.O_WRONLY, e.mode)
	if err != nil {
		return err
	}
	defer e.root.Remove(temp)
	if err = file.Chmod(e.mode); err == nil {
		_, err = file.Write(data)
	}
	if err == nil {
		err = file.Sync()
	}
	err = errors.Join(err, file.Close())
	if err != nil {
		return err
	}
	if err = checkConfinedClientEdit(e, undo); err != nil {
		return err
	}
	if err = e.root.Rename(temp, e.path); err != nil {
		return err
	}
	if runtime.GOOS == "windows" {
		return nil
	} // syncDirectory's existing platform boundary.
	dir, err := e.root.Open(filepath.Dir(e.path))
	if err != nil {
		return err
	}
	return errors.Join(dir.Sync(), dir.Close())
}

func applyClientRepairEdits(edits []clientEdit) error {
	created := []clientEdit{}
	for i, edit := range edits {
		for parent := filepath.Dir(edit.path); parent != "."; parent = filepath.Dir(parent) {
			if _, err := edit.root.Stat(parent); !os.IsNotExist(err) {
				break
			}
			created = append(created, clientEdit{root: edit.root, path: parent})
		}
		if err := applyClientEdit(edit, false); err != nil {
			// AtomicFile may report directory-sync failure after rename. Undo the current
			// edit only when its committed bytes are still exact, never a user's edit.
			if checkConfinedClientEdit(edit, true) == nil {
				err = errors.Join(err, applyClientEdit(edit, true))
			}
			for j := i - 1; j >= 0; j-- {
				err = errors.Join(err, applyClientEdit(edits[j], true))
			}
			for _, dir := range created {
				_ = dir.root.Remove(dir.path)
			}
			return err
		}
	}
	return nil
}
